"""Bundle Report Template: one PowerPoint or Word report with chosen parts of several modules.

A Bundle Report Template has four sections — PPT Dashboards, Scoring & GAP Analysis, Network Insights and Non-Qualified
Calls — in the order the user chooses, each with its sub-modules (the Dashboards, the results tabs of Scoring and the
panels of Network Insights and Non-Qualified Calls) in its own order, and the charts and tables of each sub-module.
Common filters (NR Mode, Operators, Vendors and area) apply to every section and replace the saved filters of the
Dashboards (the NR Mode lists the Dashboards); each section has its own Campaigns (which choose its CDRs) and its own
options (the scorings, environments, methodology and GAP reference of Scoring, the technology, Split by and
thresholds of Network Insights, the periods of Non-Qualified Calls).

Each section is generated by its module, its slides are copied into one deck (pptx_compose) and every chart or table
spread over several slides is put on one slide; small consecutive components of a section share a slide. The Word
version packs the components of each section on portrait pages after a table of contents in the report theme: each page
takes the next components that fit, never mixing sections, and what does not fit whole in what is left of a page (a
part, a topic, a component or its pages) starts the next one (pptx_to_docx.pack_pages).

Reports saved as favourites (``bundle_report_templates``) travel with the Reporting Jobs in exports, transfers and backups,
and a Reporting Job can include them as an artifact.
"""
