def _section_entries(section: SectionDeck, *, module_cover: bool = False) -> list[Entry]:
    """The slides of a section in the order of its sub-modules: the report cover each module starts with (unless
    ``module_cover``, for the export of the module on its own) and the closing slides left out, each block (after a
    cover, such as a scoring or an environment) ordered on its own."""
    entries: list[Entry] = []
    for item_key, content in section.decks:
        presentation = compose.deck(content)
        size = (int(presentation.slide_width), int(presentation.slide_height))
        for index, slide in enumerate(presentation.slides):
            if compose.is_closing(slide):
                continue
            tag = compose.slide_tag(slide)
            if item_key is None and index == 0 and compose.is_cover(slide) and not module_cover:
                continue
            if item_key is not None:
                item = item_key
            elif section.key == 'scoring':
                item = SCORING_TAGS.get(tag, 'cover')
            else:
                item = tag or 'selection'
            entries.append(Entry(section.key, item, slide, compose.is_cover(slide), size))
    rank = {key: position for position, key in enumerate(section.order)}
    ordered: list[Entry] = []
    block: list[Entry] = []
    for entry in [*entries, None]:
        if entry is None or entry.cover:
            ordered.extend(sorted(block, key=lambda item: -1 if item.item == 'selection' else rank.get(item.item, len(rank))))
            block = []
            if entry is not None:
                ordered.append(entry)
            continue
        block.append(entry)
    return ordered


def _components(entries: list[Entry]) -> list[Component]:
    """Covers, and the charts and tables: the slides of one spread over several slides are one component."""
    components: list[Component] = []
    for entry in entries:
        previous = components[-1] if components else None
        # A slide whose title ends in a page number continues the previous one of the same title (whose first page
        # may have none).
        if (previous is not None and not entry.cover and not previous.cover and previous.item == entry.item
                and compose.is_continued(entry.slide)
                and [compose.base_title(text) for text in compose.title_parts(entry.slide)] == list(previous.title)):
            previous.slides.append(entry.slide)
            continue
        components.append(Component(entry.section, entry.item, [entry.slide], entry.cover, entry.size))
    return components


# The pages of a chart or table that cannot become one table share a slide down to this share of their size; smaller,
# they continue on more slides.
PAGE_MINIMUM_SCALE = 0.6


def _place_component(composer: compose.DeckComposer, component: Component, legible_font: int = compose.LEGIBLE_FONT) -> list[Any]:
    """The component on one slide of ``composer`` (its slides): its pages joined (tables) or side by side, as large as
    they fit; a table that would need a font smaller than ``legible_font`` there continues on more slides."""
    copies = [composer.add_slide(slide, component.size) for slide in component.slides]
    target = copies[0]
    pages = [target]
    if len(copies) > 1:
        title, subtitle = component.title
        if compose.join_table_pages(composer, copies):
            blocks = [compose.Block(target, compose.content_shapes(target))]
            # A long or wide table keeps readable text: its rows continue in tables side by side, and on more slides
            # when even so its values would be too small.
            frame = compose.content_frame(target, composer.width, composer.height, [blocks[0].box])
            pages = compose.split_table(composer, target, compose.table_slides(target, frame, legible_font=legible_font))
            if not all(compose.fit_table(page, frame) is not None for page in pages) and any(block.shapes for block in blocks):
                compose.merge_onto_slide(composer, target, blocks, captions=False)
        elif compose.join_panel_pages(composer, copies):
            # Tables side by side (such as one per network) continue together on as few slides as keep them legible.
            frame = compose.content_frame(target, composer.width, composer.height, [compose.bounds(compose.content_shapes(target))])
            pages = compose.split_panels(composer, target, frame, legible_font)
        else:
            # Other pages share a slide side by side or one under the other, and continue on more slides when they
            # would be too small to read.
            groups = compose.page_groups(composer, copies, PAGE_MINIMUM_SCALE)
            pages = [copies[group[0]] for group in groups]
            for group in groups:
                blocks = [compose.Block(copies[index], compose.content_shapes(copies[index])) for index in group]
                if len(group) > 1 and any(block.shapes for block in blocks):
                    compose.merge_onto_slide(composer, copies[group[0]], blocks, captions=False)
        kept = [page.part for page in pages]
        for slide in copies[1:]:
            if slide.part not in kept and slide.part in [item.part for item in composer.presentation.slides]:
                composer.remove_slide(slide)
        for number, page in enumerate(pages, start=1):
            compose.set_title(page, f'{title} · {number}/{len(pages)}' if len(pages) > 1 else title, subtitle)
    for page in pages:
        # Every module's title fits on one line here, so it never covers the content under it.
        fit_slide_title(page)
        compose.tag(page, component.section)
    return pages


COVER_TITLE_PT = 54
SECTION_COVER_TITLE_PT = 48
COVER_SUBTITLE_PT = 22
COVER_BLOCKS_TOP_INCHES = 5.85


def _cover(composer: compose.DeckComposer, title: str, subtitle: str, blocks: list[tuple[str, list[str]]], section: str,
           title_size: float = COVER_TITLE_PT) -> Any:
    """A cover with its large title, its subtitle and, under the line of the layout, blocks of white lines each with its
    heading (such as the common filters and the options of a section)."""
    from pptx.dml.color import RGBColor
    from pptx.util import Inches, Pt

    from src.modules.cdr_reporting import _set_structural_slide_text
    from src.modules.exports import remove_empty_placeholders

    slide = composer.add_layout_slide('Title Page')
    _set_structural_slide_text(slide, title, subtitle)
    for shape in slide.placeholders:
        kind = shape.placeholder_format.type
        size = title_size if kind in {1, 3} else COVER_SUBTITLE_PT if kind == 4 else None
        if size is None or not shape.has_text_frame:
            continue
        for paragraph in shape.text_frame.paragraphs:
            for run in paragraph.runs:
                run.font.size = Pt(size)
    remove_empty_placeholders(slide)
    top = Inches(COVER_BLOCKS_TOP_INCHES)
    width = composer.width - Inches(1.04)
    for heading, lines in blocks:
        lines = [line for line in lines if line]
        if not lines:
            continue
        # About 110 characters fit a line at 10.5pt across the narrower portrait cover of the Word version.
        rows = (1 if heading else 0) + sum(max(1, -(-len(line) // 110)) for line in lines)
        box = slide.shapes.add_textbox(Inches(0.52), top, width, Inches(0.19 * rows + 0.06))
        frame = box.text_frame
        frame.word_wrap = True
        frame.margin_left = frame.margin_right = frame.margin_top = frame.margin_bottom = 0
        texts = ([(heading, True)] if heading else []) + [(line, False) for line in lines]
        for index, (text, bold) in enumerate(texts):
            paragraph = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
            run = paragraph.add_run()
            run.text = text
            run.font.size, run.font.bold, run.font.color.rgb = Pt(11 if bold else 10.5), bold, RGBColor(0xFF, 0xFF, 0xFF)
        # The blocks stand apart, so the common filters and the options of the section read as two groups.
        top += box.height + Inches(0.24)
    compose.tag(slide, section)
    return slide


def _compose_section(composer: compose.DeckComposer, section: SectionDeck, entries: list[Entry]) -> None:
    """The slides of ``entries`` (a section) in ``composer``: each component on one slide (see _place_component) and
    small consecutive charts and tables sharing a slide, each under its caption."""
    # (component, slide, whether the component continues on other slides)
    placed: list[tuple[Component, Any, bool]] = []
    for component in _components(entries):
        pages = _place_component(composer, component)
        placed.extend((component, page, len(pages) > 1) for page in pages)
    index = 0
    while index < len(placed):
        component, slide, split = placed[index]
        group = [(component, slide)]
        if not component.cover and not split:
            while index + len(group) < len(placed) and len(group) < COMPACT_MAXIMUM:
                candidate, candidate_slide, candidate_split = placed[index + len(group)]
                if candidate.cover or candidate_split:
                    break
                blocks = [compose.Block(item_slide, compose.content_shapes(item_slide), item.title)
                          for item, item_slide in [*group, (candidate, candidate_slide)]]
                if not compose.fits_together(composer, blocks, COMPACT_SCALE):
                    break
                group.append((candidate, candidate_slide))
        if len(group) > 1:
            items = {item.item for item, _slide in group}
            heading = section.item_titles.get(next(iter(items)), section.title) if len(items) == 1 else section.title
            # A caption does not repeat the title of the slide: its subtitle is its caption then.
            blocks = [compose.Block(item_slide, compose.content_shapes(item_slide),
                                    (item.title[1], '') if item.title[0] == heading and item.title[1] else item.title)
                      for item, item_slide in group]
            compose.merge_onto_slide(composer, slide, blocks, captions=True)
            compose.set_title(slide, heading, '')
            for _item, other in group[1:]:
                composer.remove_slide(other)
        index += len(group)


def _nest_transitions(slides: list[Any]) -> None:
    """The transitions of a module inside its section of a Bundle Report Template, one level down; a module whose own cover
    stays (each Dashboard) has it as a transition of the second level and its transitions one more level down."""
    depth = 1
    for slide in slides:
        if report_structure.level(slide) is not None:
            report_structure.shift(slide, depth)
        elif compose.is_cover(slide):
            report_structure.mark(slide, 2)
            depth = 2


def _add_closing(composer: compose.DeckComposer) -> None:
    """The closing slide of the template, when it has one."""
    if any(str(layout.name or '').strip().casefold() in compose.CLOSING_LAYOUTS
           for master in composer.presentation.slide_masters for layout in master.slide_layouts):
        composer.add_layout_slide(next(iter(compose.CLOSING_LAYOUTS)))


def compose_powerpoint(template: Path, title: str, subtitle: str, common_filters: list[str], sections: list[SectionDeck],
                       titles: dict[str, str], generated: str = '') -> tuple[bytes, list[dict[str, Any]], list[int]]:
    """The PowerPoint of a Bundle Report Template, its outline (the title of each slide) and the position of its covers (the
    report cover, then that of each section)."""
    composer = compose.DeckComposer(template)
    filters_line = ' · '.join(common_filters)
    covers = [_cover(composer, title, subtitle, [('Common filters', [filters_line]), ('', [generated])], 'cover')]
    outline: list[dict[str, Any]] = []
    for section in sections:
        # Each section starts with a cover: its name, its Campaigns, the common filters and its options. It is a
        # transition of the first level, and the transitions of its module are the levels below it.
        cover = _cover(composer, section.title, section.lines[0] if section.lines else '',
                       [('Common filters', [filters_line]), ('Section options', section.lines[1:])], section.key,
                       SECTION_COVER_TITLE_PT)
        report_structure.mark(cover, 1)
        covers.append(cover)
        first = len(composer.presentation.slides)
        _compose_section(composer, section, _section_entries(section))
        _nest_transitions(list(composer.presentation.slides)[first:])
    _add_closing(composer)
    report_structure.finish(composer.presentation)
    slides = list(composer.presentation.slides)
    for slide in slides:
        outline.append({'title': compose.title_parts(slide)[0], 'section': compose.slide_tag(slide)})
    positions = [next(index for index, slide in enumerate(slides) if slide.part is cover.part) for cover in covers]
    return composer.save(), outline, positions


def compose_word(template: Path, powerpoint: bytes, sections: list[SectionDeck],
                 covers: list[int] | None = None, *, module: bool = False,
                 theme: Any = None) -> tuple[bytes, list[dict[str, Any]]] | None:
    """The Word version: the report cover on a full page and a table of contents in ``theme`` (the active theme
    without it), then each section after its own full-page cover (``covers``: the position of the report cover and of
    each section cover in ``powerpoint``) with its components packed on portrait pages, with the sections and pages of
    the document (see word_navigation); None when LibreOffice cannot render the slides. With ``module`` (the export of
    a module on its own), the cover of the module (the first slide of ``powerpoint``) is the cover and the module has
    no section cover."""
    from src.modules.pptx_to_docx import (
        PackItem, compact_slide_image, crop_to_content, packed_component_document, portrait_covers, slide_images,
    )
    from PIL import Image
    from pptx.util import Inches

    composer = compose.DeckComposer(template, slide_height=Inches(WORD_SLIDE_HEIGHT_INCHES))
    page_width = 8.27 - 0.9
    # Slides are shown at the scale that fits their content area (the slide less its margins) across the page, so a
    # table keeps a legible font on the page.
    base = page_width / ((composer.width - Inches(0.9)) / 914400)
    legible_font = int(compose.LEGIBLE_FONT / base)
    # The covers are rendered while the components are placed and rendered, and the images are cropped at once.
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=4) as pool:
        covers_rendered = pool.submit(portrait_covers, powerpoint, covers or [0])
        plan: list[tuple[str, Any]] = []
        # The transitions inside the sections are headings with the counter they have in the PowerPoint.
        counter = report_structure.Counter()
        for position, section in enumerate(sections, start=1):
            # The export of a module has only the cover of the module; a section has its cover (or, without the
            # covers, a heading) once they are rendered.
            depth = 0
            if not module:
                plan.append(('section', (position, section, counter.next(1))))
                depth = 1
            for component in _components(_section_entries(section)):
                if component.cover:
                    slide = component.slides[0]
                    title, subtitle = compose.title_parts(slide)
                    current = report_structure.level(slide)
                    # Its level in the table of contents, under that of its section.
                    level = depth + 1
                    if current is not None:
                        title, level = f'{counter.next(current + depth)}  {title}', current + depth
                    elif not module:
                        # The cover a module keeps in its section (each Dashboard), as in _nest_transitions.
                        title, depth, level = f'{counter.next(2)}  {title}', 2, 2
                    plan.append(('heading2', PackItem('heading2', title or 'Section', [line for line in subtitle.split(' · ') if line][:3],
                                                      level=level, contents=title or 'Section')))
                    continue
                for slide in _place_component(composer, component, legible_font):
                    content = compose.content_shapes(slide)
                    shapes = content
                    title_shape = compose.title_shape(slide)
                    if title_shape is not None and title_shape.left is not None:
                        shapes = [*shapes, title_shape]
                    # Without its title too: on a page after one of the same title and context (the first line under
                    # the title), it does not repeat them.
                    untitled = None
                    if len(shapes) > len(content):
                        # The shapes beside the title (such as the logos) go with it.
                        title_bottom = title_shape.top + title_shape.height
                        untitled = compose.bounds([shape for shape in content if shape.top + shape.height > title_bottom])
                    lines = [' '.join(paragraph.text.split()) for paragraph in title_shape.text_frame.paragraphs
                             if paragraph.text.strip()] if title_shape is not None else []
                    group = '\n'.join(compose.base_title(line) for line in lines[:2])
                    plan.append(('image', (compose.bounds(shapes), untitled, component.title[0], group)))
        if not any(kind == 'image' for kind, _item in plan):
            return None
        images = slide_images(composer.save(), dpi=WORD_RENDER_DPI)
        if not images:
            return None
        slide_width, slide_height = composer.width, composer.height

        def cropped_image(image: bytes, box: tuple[int, int, int, int] | None) -> tuple[bytes, float, float]:
            share = None
            if box is not None:
                share = (box[0] / slide_width, box[1] / slide_height, box[2] / slide_width, box[3] / slide_height)
            cropped, _width_px, _height_px = crop_to_content(image, share)
            # The blank bands inside a component (such as the space above its footnote) shrink too.
            cropped = compact_slide_image(cropped)
            with Image.open(BytesIO(cropped)) as raster:
                width_px, height_px = raster.size
            width, height = width_px / WORD_RENDER_DPI * base, height_px / WORD_RENDER_DPI * base
            if width > page_width:
                width, height = page_width, height * page_width / width
            return cropped, width, height

        def image_item(image: bytes, entry: tuple[Any, ...]) -> PackItem:
            box, untitled_box, caption, group = entry
            cropped, width, height = cropped_image(image, box)
            untitled, untitled_width, untitled_height = (cropped_image(image, untitled_box) if untitled_box is not None
                                                         else (b'', 0.0, 0.0))
            return PackItem('image', caption, image=cropped, width=width, height=height, group=group, untitled=untitled,
                            untitled_width=untitled_width, untitled_height=untitled_height)

        entries = [item for kind, item in plan if kind == 'image']
        image_items = iter(list(pool.map(image_item, images, entries)))
        pages = covers_rendered.result() or []
    items: list[Any] = []
    for kind, item in plan:
        if kind == 'image':
            items.append(next(image_items))
        elif kind == 'section':
            position, section, number = item
            listed = {'level': 1, 'contents': f'{number}  {section.title}'}
            items.append(PackItem('cover', section.title, image=pages[position], **listed) if position < len(pages)
                         else PackItem('heading1', section.title, list(section.lines), **listed))
        else:
            items.append(item)
    page_items: list[list[Any]] = []
    cover = [PackItem('cover', 'Cover', image=pages[0])] if pages else []
    from src.modules.scoring_themes import active_theme, get_theme
    document = packed_component_document([*cover, *items], None, page_items, get_theme(theme) if theme else active_theme())
    return document, word_navigation(page_items)


