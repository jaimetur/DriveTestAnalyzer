def module_document(key: str, content: bytes, export_format: str, title: str = '', theme: Any = None) -> bytes:
    """The PowerPoint or Word export of a module on its own (``key``: scoring, network_insights or
    non_qualified_calls) from the deck its module generated (``content``): the same composition as its section of a
    Bundle Report Template, so both exports always look alike. Word packs the components on portrait pages after the cover
    of the module and a table of contents in ``theme`` (the active theme without it; one page per slide when LibreOffice
    is not available)."""
    from src.config import settings

    template = settings.powerpoint_template
    section = SectionDeck(key, title, [], decks=[(None, content)], item_titles=module_item_titles(key))
    powerpoint = compose_module_powerpoint(template, section)
    if export_format != 'word':
        return powerpoint
    packed = compose_word(template, content, [section], [0], module=True, theme=theme)
    if packed is None:
        from src.modules.pptx_to_docx import pptx_to_docx
        return pptx_to_docx(powerpoint, title)
    return packed[0]


def word_navigation(page_items: list[list[Any]]) -> list[dict[str, Any]]:
    """The sections of the Word version and their pages (numbered from 0), named after what they show: the cover of
    the report, then each section from its cover."""
    groups: list[dict[str, Any]] = []
    for index, items in enumerate(page_items):
        first = items[0] if items else None
        if first is not None and first.kind == 'cover':
            groups.append({'title': first.text or 'Cover', 'pages': [{'index': index, 'title': 'Cover'}]})
            continue
        names = [item.text for item in items if item.kind == 'image' and item.text]
        headings = [item.text for item in items if item.kind != 'image' and item.text]
        title = ' · '.join(dict.fromkeys(names)) or ' · '.join(headings) or f'Page {index + 1}'
        if not groups:
            groups.append({'title': 'Report', 'pages': []})
        groups[-1]['pages'].append({'index': index, 'title': title[:140]})
    return groups


def powerpoint_navigation(outline: list[dict[str, Any]], titles: dict[str, str]) -> list[dict[str, Any]]:
    """The sections of the PowerPoint and their slides (numbered from 0), each slide named by its title."""
    groups: list[dict[str, Any]] = []
    for index, item in enumerate(outline):
        section = item.get('section') or ''
        name = 'Cover' if section == 'cover' else titles.get(section, '')
        if not groups or (name and groups[-1]['key'] != section):
            groups.append({'key': section, 'title': name or 'Closing', 'pages': []})
        groups[-1]['pages'].append({'index': index, 'title': item.get('title') or f'Slide {index + 1}'})
    return [{'title': group['title'], 'pages': group['pages']} for group in groups]


# -- the generators of each section ------------------------------------------------------
class SectionGenerator:
    """Generates the decks of each section with its module, as ``user`` in ``repository`` (the active workspace)."""

    def __init__(self, core: Any, repository: Any, user: Any, definition: dict[str, Any], folder: Path,
                 progress: Callable[[str], None] = lambda _message: None):
        self.core, self.repository, self.user = core, repository, user
        self.definition, self.folder, self.progress = definition, folder, progress
        self.filters = definition['filters']

    def cities(self) -> list[str]:
        cities = list(self.filters['cities'])
        if self.filters['main_cities']:
            cities = list(dict.fromkeys([*cities, *self.repository.list_main_cities()]))
        return cities

    def dashboards(self, section: dict[str, Any]) -> SectionDeck:
        tools = getattr(self.core, 'dashboard_reporting', None)
        if tools is None:
            raise BundleReportTemplateError('PPT Dashboards are not available.')
        stored = tools.list_dashboards(self.repository)
        names = {str(key): str(value.get('name') or key) for key, value in stored.items() if isinstance(value, dict)}
        deck = SectionDeck('dashboards', '', [], order=[item['key'] for item in section['items']], item_titles=names)
        for item in section['items']:
            dashboard = stored.get(item['key'])
            if not isinstance(dashboard, dict):
                deck.lines.append(f"{item.get('label') or item['key']}: the Dashboard no longer exists")
                continue
            # The NR Mode of the report chooses its Dashboards: each Dashboard is made for the KPIs of one NR Mode.
            nr_mode = 'SA' if str(dashboard.get('technology') or '').casefold() == 'sa' else 'NSA'
            if nr_mode != self.filters['nr_mode']:
                continue
            self.progress(f"Generating the Dashboard {names.get(item['key'])}")
            definition = dict(dashboard)
            definition.pop('datasets', None)
            filters = {name: values for name, values in (definition.get('filters') or {}).items()
                       if name not in {*DASHBOARD_FILTERS.values(), 'Campaign'}}
            if section['options']['campaigns']:
                # The Campaigns of the section choose the CDRs of every Dashboard.
                filters['Campaign'] = list(section['options']['campaigns'])
            from src.modules.ppt_dashboards import MAIN_CITIES
            for field_name, column in DASHBOARD_FILTERS.items():
                values = list(self.filters[field_name])
                if field_name == 'cities' and self.filters['main_cities']:
                    values = [MAIN_CITIES, *values]
                if values:
                    filters[column] = values
            definition.update({'filters': filters, 'auto_cdrs': True})
            job_id = tools.queue_export(item['key'], self.user, definition, theme=self.definition.get('theme'))
            deadline = time.monotonic() + DASHBOARD_TIMEOUT_SECONDS
            while True:
                row = tools.job(self.repository, job_id)
                if row is None:
                    raise BundleReportTemplateError('The Dashboard PPT job was deleted.')
                if str(row['status']) == 'ready':
                    break
                if str(row['status']) in {'failed', 'stopped'}:
                    raise BundleReportTemplateError(str(row['last_error'] or f"The Dashboard PPT job {row['status']}."))
                if time.monotonic() > deadline:
                    raise BundleReportTemplateError('The Dashboard PPT job did not finish within three hours.')
                self.progress(f"Generating the Dashboard {names.get(item['key'])} ({int(row['progress'] or 0)}%)")
                time.sleep(2)
            deck.decks.append((item['key'], Path(str(row['output_path'])).read_bytes()))
        if not deck.decks:
            raise BundleReportTemplateError(f"None of the chosen Dashboards is a {self.filters['nr_mode']} Dashboard.")
        return deck

    def scoring(self, section: dict[str, Any]) -> SectionDeck:
        options = section['options']
        if options.get('nsa_vs_sa'):
            # The NSA and SA CDRs of its campaigns side by side: Latest campaign is the newest quarter with both.
            from src.modules.scoring_selection import expand_scoring_campaigns
            nr_mode = NSA_VS_SA
            campaigns = expand_scoring_campaigns(self.repository, nr_mode, options['campaigns'])
        else:
            nr_mode = self.filters['nr_mode']
            campaigns = resolve_campaign_filter(self.repository, nr_mode, options['campaigns'])
        dataset_ids, incomplete = complete_campaign_cdrs(self.repository, nr_mode, campaigns)
        if not dataset_ids:
            missing = f" ({', '.join(incomplete)} lack a CDR type)" if incomplete else ''
            raise BundleReportTemplateError(f'There is no campaign with Data, Voice and Speech {nr_mode_label(nr_mode)} CDRs '
                                            f'to score{missing}.')
        chosen = {item['key']: item for item in section['items']}
        environments = [name for name in options['environments'] if name != COMBINED_ENVIRONMENT]
        names = ['All Environments' if name == COMBINED_ENVIRONMENT else name for name in options['environments']]

        def content(kind: str) -> dict[str, Any]:
            groups = {}
            for key, _title, components in SCORING_SUBMODULES:
                item = chosen.get(key)
                groups[key] = {name: bool(item and item['components'].get(name)) for name, _label in components}
            groups['tables'].update({'kpi_values': options['kpi_values'], 'gap_values': options['gap_values']})
            scenario_options = {'enabled': kind in options['scorings'], 'environments': 'split' if environments else 'all', **groups}
            if environments:
                scenario_options['environment_names'] = names
            return scenario_options

        context_filters = {column: list(self.filters[name]) for name, column in SCORING_FILTERS.items() if self.filters[name]}
        report = {'theme': self.definition['theme'], 'all_operators': options['all_operators'], 'scenarios': [{
            'name': report_title(self.definition), 'context_filters': context_filters,
            'main_cities': self.filters['main_cities'], 'aggregation_levels': ['Operator', 'Campaign'],
            'scorings': {kind: content(kind) for kind, _label in SCORINGS},
            'area_summary': {**options['area_summary'], 'enabled': True},
        }]}
        base = {'dataset_ids': dataset_ids, 'nr_mode': nr_mode, 'baseline_operator': options['baseline_operator'],
                'scoring_profile_id': options['methodology'] or None,
                # A Saved Filter already calculated for these CDRs and filters (such as a Favourites Filter) is used as it is.
                'reuse_saved_filters': True}
        self.progress('Calculating Scoring & GAP Analysis')
        try:
            content_bytes, _filename, _job = self.core.build_scoring_report_document(self.repository, base, report, self.user.username)
        except ValueError as exc:
            raise BundleReportTemplateError(str(exc)) from exc
        titles = {key: title for key, title, _components in SCORING_SUBMODULES}
        return SectionDeck('scoring', '', [], decks=[(None, content_bytes)], order=[item['key'] for item in section['items']],
                           item_titles=titles)

    def network_selection(self, section: dict[str, Any]) -> dict[str, Any]:
        """The Network Insights selection of the section: the common filters, its Campaigns and its options."""
        options = section['options']
        nr_mode = self.filters['nr_mode']
        campaigns = list(options['campaigns'])
        if campaign_presets(campaigns):
            resolved = resolve_campaign_filter(self.repository, nr_mode, campaigns)
            campaigns = sort_campaigns({compact_campaign_value(value) or value for value in resolved})
        return {
            'nr_mode': nr_mode, 'datasets': {}, 'technology': options['technology'], 'group': list(options['group']),
            'operators': list(self.filters['operators']), 'operator_vendors': list(self.filters['operator_vendors']),
            'vendor_operators': list(self.filters['vendor_operators']), 'vendors': list(self.filters['vendors']),
            'campaigns': campaigns, 'regions': list(self.filters['regions']), 'clusters': list(self.filters['clusters']),
            'cities': self.cities(), 'environments': list(options['environments']),
            **{name: options[name] for name in ('coverage_threshold', 'interference_threshold', 'nr_coverage_threshold',
                                                'nr_interference_threshold', 'overshoot_km', 'grid_metres')},
        }

    def network_insights(self, section: dict[str, Any]) -> SectionDeck:
        selection = self.network_selection(section)
        components = [f"{item['key']}.{name}" for item in section['items'] for name, chosen in item['components'].items() if chosen]
        destination = self.folder / 'network-insights.pptx'
        self.progress('Analysing Network Insights')
        try:
            self.core.write_network_insights_summary(selection, 'powerpoint', destination, components=components, compose=False,
                                                     theme=self.definition['theme'])
        except Exception as exc:  # The module reports its own errors (HTTPException included).
            raise BundleReportTemplateError(str(getattr(exc, 'detail', exc))) from exc
        from src.modules.network_insights_export import REPORT_PANELS
        return SectionDeck('network_insights', '', [], decks=[(None, destination.read_bytes())],
                           order=[item['key'] for item in section['items']], item_titles={key: title for key, title, _items in REPORT_PANELS})

    def non_qualified_calls(self, section: dict[str, Any]) -> SectionDeck:
        from src.modules.report_tasks import ARTIFACT_PROVIDERS
        from src.modules.non_qualified_calls_export import REPORT_PANELS

        provider = ARTIFACT_PROVIDERS.get('non_qualified_calls')
        if provider is None:
            raise BundleReportTemplateError('Non-Qualified Calls are not available.')
        options = section['options']
        filters = {column: list(self.filters[name]) for name, column in NQ_FILTERS.items() if self.filters.get(name)}
        if self.filters['main_cities']:
            filters['city'] = self.cities()
        filters['nr_mode'] = [self.filters['nr_mode']]
        if options['campaigns']:
            filters['campaign'] = list(options['campaigns'])
        components = [f"{item['key']}.{name}" for item in section['items'] for name, chosen in item['components'].items() if chosen]
        config = {'formats': ['powerpoint'], 'options': {
            'filters': filters, 'granularity': options['granularity'], 'open_only': '1' if options['open_only'] else '',
            'include_suggestions': '1' if options['include_suggestions'] else '',
            'show_not_classified': '1' if options['show_not_classified'] else '', 'show_empty': '1' if options['show_empty'] else '',
            'components': components, 'compose': False,
        }}
        self.progress('Summarising Non-Qualified Calls')
