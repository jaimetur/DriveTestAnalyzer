def _json_hash(value: Any) -> str:
    import hashlib
    return hashlib.sha256(json.dumps(value, sort_keys=True, default=str).encode('utf-8')).hexdigest()


def _calls_signature(repository: Any) -> list[Any]:
    """What changes with any change to the Non-Qualified Calls: the rows of every table of the module."""
    from src.modules.non_qualified_calls import NQ_TABLE_TITLES

    signature = []
    with repository.connection() as connection:
        for table in sorted(NQ_TABLE_TITLES):
            try:
                columns = {str(row[1]) for row in connection.execute(f'PRAGMA table_info({table})')}
                if not columns:
                    continue
                changed = ', MAX(updated_at)' if 'updated_at' in columns else ''
                signature.append([table, *connection.execute(f'SELECT COUNT(*), MAX(rowid){changed} FROM {table}').fetchone()])
            except sqlite3.Error:
                continue
    return signature


def _saved_filters_signature(repository: Any) -> list[Any]:
    """What changes when a Saved Filter is calculated again (the Scoring section uses their results)."""
    try:
        with repository.connection() as connection:
            return list(connection.execute(
                'SELECT COUNT(*), MAX(updated_at), MAX(finished_at), SUM(calculation_count) FROM saved_filters').fetchone())
    except sqlite3.Error:
        return []


def section_fingerprint(core: Any, repository: Any, definition: dict[str, Any], section: dict[str, Any],
                        generator: 'SectionGenerator') -> str:
    """Identity of a generated section: its options and the common filters, and every input its module reads (the
    CDRs, the Operator and Vendor Maps, the Main Cities and, per module, the Dashboards, the methodologies and the Saved
    Filters calculated, the inventory of the analysis or the follow-up of the calls). The same identity means the same
    document; a change of any input generates it again."""
    inputs: dict[str, Any] = {
        'version': SECTION_CACHE_VERSION, 'section': section, 'filters': definition['filters'],
        # The theme of the report colours every section that supports themes.
        'theme': definition.get('theme'),
        'datasets': [dict(row) for row in repository.list_datasets()],
        'operators': repository.list_operator_mapping_groups(), 'vendors': repository.list_vendor_mapping_groups(),
        'main_cities': list(repository.list_main_cities()),
    }
    if section['key'] == 'dashboards':
        stored = core.dashboard_reporting.list_dashboards(repository)
        inputs['dashboards'] = {item['key']: stored.get(item['key']) for item in section['items']}
    elif section['key'] == 'scoring':
        inputs['methodologies'] = repository.get_scoring_profiles()
        # A Saved Filter of the same selection is used as it is: calculating one again generates the section again.
        inputs['saved_filters'] = _saved_filters_signature(repository)
    elif section['key'] == 'network_insights':
        inputs['analysis'] = core.network_insights_summary_key(generator.network_selection(section))
    elif section['key'] == 'non_qualified_calls':
        inputs['calls'] = _calls_signature(repository)
    return _json_hash(inputs)


def _section_lock(key: str) -> Lock:
    with _section_locks_guard:
        return _section_locks.setdefault(key, Lock())


def _cached_section(root: Path, key: str) -> SectionDeck | None:
    folder = root / key
    meta = folder / 'section.json'
    if not meta.is_file() or time.time() - meta.stat().st_mtime > SECTION_CACHE_HOURS * 3600:
        return None
    try:
        data = json.loads(meta.read_text(encoding='utf-8'))
        decks = [(entry['item'], (folder / entry['file']).read_bytes()) for entry in data['decks']]
    except (OSError, ValueError, KeyError, TypeError):
        return None
    deck = SectionDeck(data['key'], '', list(data.get('lines') or []), decks=decks, order=list(data.get('order') or []),
                       item_titles=dict(data.get('item_titles') or {}))
    deck.generated_at = str(data.get('generated_at') or '')
    return deck


def _store_section(root: Path, key: str, deck: SectionDeck) -> None:
    folder = root / key
    folder.mkdir(parents=True, exist_ok=True)
    entries = []
    for index, (item, content) in enumerate(deck.decks):
        (folder / f'deck-{index}.pptx').write_bytes(content)
        entries.append({'item': item, 'file': f'deck-{index}.pptx'})
    temporary = folder / 'section.json.tmp'
    temporary.write_text(json.dumps({'key': deck.key, 'lines': deck.lines, 'order': deck.order, 'item_titles': deck.item_titles,
                                     'decks': entries, 'generated_at': datetime.now().isoformat(timespec='seconds')}),
                         encoding='utf-8')
    temporary.replace(folder / 'section.json')


def forget_old_sections(root: Path) -> None:
    """Generated sections and composed documents older than a day are deleted."""
    if not root.is_dir():
        return
    limit = time.time() - SECTION_CACHE_HOURS * 3600
    for folder in root.iterdir():
        if folder.name == DOCUMENT_CACHE_FOLDER:
            for document in folder.iterdir() if folder.is_dir() else []:
                meta = document / 'document.json'
                if document.is_dir() and (not meta.is_file() or meta.stat().st_mtime < limit):
                    shutil.rmtree(document, ignore_errors=True)
            continue
        meta = folder / 'section.json'
        if folder.is_dir() and (not meta.is_file() or meta.stat().st_mtime < limit):
            shutil.rmtree(folder, ignore_errors=True)


def document_key(template: Path, title: str, subtitle: str, filters: list[str], decks: list[SectionDeck],
                 section_keys: list[str | None]) -> str | None:
    """The identity of a composed document: its sections as generated (their cache keys), titles, cover lines,
    common filters and template; None when a section has no identity."""
    if not section_keys or any(key is None for key in section_keys):
        return None
    try:
        stat = template.stat()
        template_identity = [stat.st_size, stat.st_mtime_ns]
    except OSError:
        template_identity = None
    import hashlib
    payload = {'version': DOCUMENT_CACHE_VERSION, 'sections': section_keys, 'title': title, 'subtitle': subtitle,
               'filters': filters, 'decks': [[deck.key, deck.title, deck.lines] for deck in decks],
               'template': template_identity}
    return hashlib.sha256(json.dumps(payload, sort_keys=True, default=str).encode('utf-8')).hexdigest()


def document_folder(root: Path, key: str) -> Path:
    return root / DOCUMENT_CACHE_FOLDER / key


def _cached_document(root: Path, key: str) -> dict[str, Any] | None:
    """The composed document kept for ``key``: its PowerPoint and outline, and the packed Word when it has one."""
    folder = document_folder(root, key)
    meta = folder / 'document.json'
    if not meta.is_file() or time.time() - meta.stat().st_mtime > SECTION_CACHE_HOURS * 3600:
        return None
    try:
        data = json.loads(meta.read_text(encoding='utf-8'))
        document = {'powerpoint': (folder / 'document.pptx').read_bytes(), 'outline': list(data['outline']),
                    'navigation': list(data['navigation']), 'covers': list(data.get('covers') or []),
                    'generated_at': str(data.get('generated_at') or ''), 'word': None, 'word_navigation': None}
        if (folder / 'document.docx').is_file() and isinstance(data.get('word_navigation'), list):
            document['word'] = (folder / 'document.docx').read_bytes()
            document['word_navigation'] = data['word_navigation']
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return document


def _store_document(root: Path, key: str, powerpoint: bytes, outline: list[dict[str, Any]], navigation: list[dict[str, Any]],
                    covers: list[Any], word: bytes | None = None, word_navigation: list[dict[str, Any]] | None = None) -> None:
    folder = document_folder(root, key)
    folder.mkdir(parents=True, exist_ok=True)
    meta = folder / 'document.json'
    try:
        data = json.loads(meta.read_text(encoding='utf-8')) if meta.is_file() else {}
    except (OSError, ValueError):
        data = {}
    (folder / 'document.pptx').write_bytes(powerpoint)
    data.update(outline=outline, navigation=navigation, covers=covers,
                generated_at=data.get('generated_at') or datetime.now().isoformat(timespec='seconds'))
    if word is not None:
        (folder / 'document.docx').write_bytes(word)
        data['word_navigation'] = word_navigation or []
    temporary = folder / 'document.json.tmp'
    temporary.write_text(json.dumps(data, default=str), encoding='utf-8')
    temporary.replace(meta)


def cached_preview(root: Path | None, key: str | None, suffix: str) -> tuple[bytes | None, list[bytes]] | None:
    """The preview (its PDF and page images) kept with a composed document, or None."""
    if root is None or key is None:
        return None
    folder = document_folder(root, key)
    pages = sorted(folder.glob(f'preview-{suffix}-*.png'), key=lambda path: int(path.stem.rsplit('-', 1)[1]))
    pdf = folder / f'preview-{suffix}.pdf'
    if not pages and not pdf.is_file():
        return None
    try:
        return (pdf.read_bytes() if pdf.is_file() else None), [page.read_bytes() for page in pages]
    except OSError:
        return None


def store_preview(root: Path | None, key: str | None, suffix: str, pdf: bytes | None, pages: list[bytes]) -> None:
    if root is None or key is None or not document_folder(root, key).is_dir():
        return
    folder = document_folder(root, key)
    if pdf:
        (folder / f'preview-{suffix}.pdf').write_bytes(pdf)
    for index, image in enumerate(pages):
        (folder / f'preview-{suffix}-{index}.png').write_bytes(image)


def build_report(core: Any, repository: Any, user: Any, definition: dict[str, Any], export_format: str, folder: Path, *,
                 name: str = '', section_titles: dict[str, str] | None = None,
                 progress: Callable[[int, str], None] = lambda _percent, _message: None,
                 cache_root: Path | None = None, reuse: bool = True,
                 on_powerpoint: Callable[[bytes, str | None, bool], None] | None = None) -> BuildResult:
    """Generate every chosen section with its module and compose the PowerPoint (and the Word version).

    With ``cache_root``, each generated section is kept there and used again by the next exports while its identity
    (``section_fingerprint``) does not change, unless ``reuse`` is False; two exports that need the same section at
    once generate it once."""
    definition = normalize_definition(definition)
    sections = [section for section in enabled_sections(definition) if core.user_has_feature(user, SECTION_FEATURES[section['key']])]
    if not sections:
        raise BundleReportTemplateError('Check at least one section with a sub-module that your account can use.')
    titles = {**SECTION_TITLES, **(section_titles or {})}
    try:
        profiles = repository.get_scoring_profiles()
        methodology_names = {profile['id']: profile.get('name') or profile['id'] for profile in profiles['profiles']}
    except (ValueError, AttributeError):
        methodology_names = {}
    warnings: list[str] = []
    reused: list[str] = []
    decks: list[SectionDeck] = []
    section_keys: list[str | None] = []
    total = len(sections)
    for position, section in enumerate(sections):
        share = (position / total) * 80

        def report(message: str, share=share) -> None:
            progress(int(5 + share), message)

        generator = SectionGenerator(core, repository, user, definition, folder, report)
        try:
            key = section_fingerprint(core, repository, definition, section, generator) if cache_root is not None else None
        except Exception:  # noqa: BLE001 - a section whose identity cannot be known is generated.
            key = None
        try:
            with _section_lock(key) if key else nullcontext():
                deck = _cached_section(cache_root, key) if key and reuse else None
                if deck is not None:
                    reused.append(section['key'])
                    report(f"Using {titles[section['key']]} generated at {deck.generated_at.replace('T', ' ')[:16]}")
                else:
                    deck = getattr(generator, section['key'])(section)
                    if key:
                        _store_section(cache_root, key, deck)
        except Exception as exc:  # A section that fails leaves the others in the report.
            warnings.append(f"{titles[section['key']]}: {getattr(exc, 'detail', exc)}")
            continue
        deck.title = titles[section['key']]
        dashboards = deck.item_titles if section['key'] == 'dashboards' else None
        deck.lines = [*section_lines(section, dashboards, methodology_names), *deck.lines]
        decks.append(deck)
        section_keys.append(key)
    if not decks:
        raise BundleReportTemplateError(' '.join(warnings) or 'No section could be generated.')
    from src.config import settings
    template = settings.powerpoint_template
    title = report_title(definition, name)
    filters = common_filter_items(definition)
    key = document_key(template, title, definition['subtitle'], filters, decks, section_keys) if cache_root is not None else None
    # The same sections, titles and filters give the same document: an earlier export composed (and packed) it.
    document = _cached_document(cache_root, key) if key and reuse else None
    if document is not None:
        stamp = document['generated_at'].replace('T', ' ')[:16]
        progress(86, f'Using the PowerPoint composed at {stamp}')
        powerpoint, outline, covers = document['powerpoint'], document['outline'], document['covers']
    else:
        progress(86, 'Composing the PowerPoint')
        powerpoint, outline, covers = compose_powerpoint(template, title, definition['subtitle'], filters, decks, titles,
                                                         datetime.now().strftime('Generated %Y-%m-%d %H:%M'))
        if key:
            _store_document(cache_root, key, powerpoint, outline, powerpoint_navigation(outline, titles), covers)
    if on_powerpoint is not None:
        # The PowerPoint is ready (for example to render its preview while the Word pages are packed).
        on_powerpoint(powerpoint, key, document is not None)
    word = None
    navigation = slides_navigation = powerpoint_navigation(outline, titles)
    reused_document = document is not None
    if export_format == 'word':
        if document is not None and document['word'] is not None:
            progress(90, f'Using the Word pages packed at {stamp}')
            word, navigation = document['word'], document['word_navigation']
        else:
            progress(90, 'Packing the Word pages')
            packed = compose_word(template, powerpoint, decks, covers, theme=definition.get('theme'))
            # Without LibreOffice the Word document has one page per slide: the document composed is still reused.
            reused_document = reused_document and packed is None
            if packed is None:
                from src.modules.pptx_to_docx import pptx_to_docx
                warnings.append('LibreOffice is not available: the Word document has one page per slide.')
                word = pptx_to_docx(powerpoint, title)
            else:
                word, navigation = packed
                if key:
                    _store_document(cache_root, key, powerpoint, outline, powerpoint_navigation(outline, titles), covers,
                                    word, navigation)
    return BuildResult(powerpoint, word, warnings, outline, navigation, slides_navigation, reused, document_key=key,
                       document_reused=reused_document)


def definition_summary(definition: dict[str, Any]) -> dict[str, Any]:
    """What App Events record of a Bundle Report Template: its filters and the checked sections, sub-modules and options."""
    return {'filters': definition['filters'], 'sections': [{
        'key': section['key'], 'items': [item['key'] for item in section['items']],
        'components': {item['key']: [name for name, chosen in item.get('components', {}).items() if chosen] for item in section['items']
                       if 'components' in item},
        'options': section['options']} for section in enabled_sections(definition)]}


