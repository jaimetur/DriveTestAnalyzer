def filter_lines(definition: dict[str, Any]) -> list[str]:
    """The common filters as the cover shows them."""
    filters = definition['filters']
    chosen = [f"{FILTER_LABELS[name]}: {', '.join(filters[name])}" for name in FILTER_FIELDS if filters[name]]
    if filters['main_cities']:
        chosen.append('Main Cities')
    return [f"NR Mode: {filters['nr_mode']}", ' · '.join(chosen) if chosen else 'Every Operator, Vendor and area']


def common_filter_items(definition: dict[str, Any]) -> list[str]:
    """Every common filter with its values (All when it has none), as the covers show them."""
    filters = definition['filters']
    items = [f"NR Mode: {filters['nr_mode']}"]
    for name in FILTER_FIELDS:
        values = list(filters[name])
        if name == 'cities' and filters['main_cities']:
            values = ['Main Cities', *values]
        items.append(f"{FILTER_LABELS[name]}: {', '.join(values) or 'All'}")
    return items


def scope_line(options: dict[str, Any]) -> str:
    """The Campaigns of a section."""
    campaigns = [CAMPAIGN_PRESET_LABELS.get(value, value) for value in options['campaigns']]
    return f"Campaigns: {', '.join(campaigns) or 'All campaigns'}"


def section_lines(section: dict[str, Any], dashboard_names: dict[str, str] | None = None,
                  methodology_names: dict[str, str] | None = None) -> list[str]:
    """What the Campaigns and options of a section choose, as its cover shows them."""
    return [scope_line(section['options']), *_option_lines(section, dashboard_names, methodology_names)]


def _option_lines(section: dict[str, Any], dashboard_names: dict[str, str] | None,
                  methodology_names: dict[str, str] | None) -> list[str]:
    options = section['options']
    if section['key'] == 'dashboards':
        names = [item.get('label') or (dashboard_names or {}).get(item['key'], item['key']) for item in section['items']]
        return [f"Dashboards: {', '.join(names)}"]
    if section['key'] == 'scoring':
        scorings = ', '.join(label for key, label in SCORINGS if key in options['scorings'])
        environments = ', '.join('All Environments' if name == COMBINED_ENVIRONMENT else name for name in options['environments'])
        methodology = (methodology_names or {}).get(options['methodology']) or (
            'By campaign' if options['methodology'] == BY_CAMPAIGN else options['methodology'])
        area = options['area_summary']
        trend_campaigns = ', '.join(CAMPAIGN_PRESET_LABELS.get(value) or format_campaign(value) or value
                                    for value in area.get('campaigns') or []) or 'the campaigns of the section'
        cities = ', '.join([*(['Main Cities'] if area.get('main_cities') else []), *(area.get('cities') or [])])
        rows = ' and '.join(part for part in ('' if area['breakdown'] == 'None' else 'each ' + area['breakdown'], cities) if part)
        areas = (f" · Geographical Areas: {rows or 'each Region and London'}"
                 f" · time split {'All selected CDRs' if area['time_split'] == 'All' else area['time_split']}")
        every = ' · All Operators in the Focus Operators panels' if options.get('all_operators') else ''
        every += ' · NSA vs SA' if options.get('nsa_vs_sa') else ''
        return [f"{scorings} · Environments: {environments}{every}",
                f"Methodology: {methodology} · GAP reference: {options['baseline_operator']}",
                f"Scoring Trends: {trend_campaigns}{areas}"]
    if section['key'] == 'network_insights':
        group = ', '.join(NI_GROUPINGS[key] for key in options['group']) or 'All samples'
        return [f"Technology: {NI_TECHNOLOGIES[options['technology']]} · Split by: {group}",
                f"LTE RSRP < {options['coverage_threshold']:g} dBm, SINR < {options['interference_threshold']:g} dB · "
                f"NR SS-RSRP < {options['nr_coverage_threshold']:g} dBm, SS-SINR < {options['nr_interference_threshold']:g} dB · "
                f"Overshooting > {options['overshoot_km']:g} km"]
    return [f"Progress periods: {NQ_GRANULARITIES[options['granularity']]} · "
            f"{'Open calls only' if options['open_only'] else 'Every call'} · "
            f"{'Suggested root causes counted' if options['include_suggestions'] else 'Labelled root causes only'}"]


def catalogue_payload(dashboards: list[dict[str, Any]], export_panels: Any = None) -> dict[str, Any]:
    """The sections, sub-modules and components the editor lists: of Scoring & GAP Analysis, the panels the workspace
    exports (``export_panels``, see scoring_export_panels), each with the operators it exports."""
    panels = _panels()
    scoring_panels = normalize_export_panels(export_panels)

    def components_of(key: str, item_key: str, components) -> list[dict[str, Any]]:
        if key != 'scoring':
            return [{'key': name, 'title': label} for name, label in components]
        return [{'key': name, 'title': label, 'operators': scoring_panels[item_key][name]['operators']}
                for name, label in components if scoring_panels[item_key][name]['exportable']]
    return {'sections': [{
        'key': key, 'feature': feature, 'title': title,
        'items': ([{'key': item['id'], 'title': item['name'], 'nr_mode': item.get('nr_mode', ''), 'components': []} for item in dashboards]
                  if key == 'dashboards' else
                  [{'key': item_key, 'title': item_title, 'components': components_of(key, item_key, components)}
                   for item_key, item_title, components in panels[key]
                   if key != 'scoring' or components_of(key, item_key, components)]),
    } for key, feature, title in SECTIONS]}


