def _public(job: dict[str, Any]) -> dict[str, Any]:
    return {key: job[key] for key in ('id', 'status', 'progress', 'message', 'format', 'file_name', 'previews', 'warnings',
                                      'outline', 'navigation', 'created_at', 'finished_at', 'title', 'error', 'reused',
                                      'document_reused')}


def _forget_old_jobs(root: Path) -> None:
    with _jobs_lock:
        finished = sorted((job for job in _jobs.values() if job['status'] in {'ready', 'failed'}), key=lambda job: job['created_at'])
        for job in finished[:-JOBS_KEPT] if len(finished) > JOBS_KEPT else []:
            _jobs.pop(job['id'], None)
            shutil.rmtree(job['folder'], ignore_errors=True)
    if root.is_dir():
        limit = time.time() - JOB_FILES_KEPT_HOURS * 3600
        active = {str(job['folder']) for job in _jobs.values()}
        for folder in root.iterdir():
            if folder.name == SECTION_CACHE_FOLDER:
                forget_old_sections(folder)
            elif folder.is_dir() and str(folder) not in active and folder.stat().st_mtime < limit:
                shutil.rmtree(folder, ignore_errors=True)


def install_complete_report_routes(core: Any) -> None:
    from fastapi import Depends, HTTPException
    from fastapi.responses import FileResponse, Response
    from pydantic import BaseModel, Field

    app = core.app

    class FavouritePayload(BaseModel):
        name: str = ''
        definition: dict[str, Any] = Field(default_factory=dict)

    class JobPayload(BaseModel):
        definition: dict[str, Any] = Field(default_factory=dict)
        format: str = 'powerpoint'
        name: str = ''
        # Generate every section again instead of using those of earlier exports whose data has not changed.
        refresh: bool = False

    def repository_for(user) -> Any:
        if not core.active_workspace:
            raise HTTPException(409, 'Open a workspace before using Reporting.')
        core.require_workspace_access(user, core.active_workspace.id)
        repository = core.Repository(core.active_workspace.database_path, global_db_path=core.repository.global_db_path,
                                     workspace_registry_db_path=core.workspace_registry.registry_path)
        ensure_tables(repository)
        return repository

    def reporting_user(user=Depends(core.current_user)):
        if not core.user_has_feature(user, 'reporting'):
            raise HTTPException(403, 'Your account cannot use Reporting.')
        return user

    def editor_user(user=Depends(reporting_user)):
        if user.role not in {'user-editor', 'admin', 'super-admin'}:
            raise HTTPException(403, 'Editor access is required to change favourite Complete Reports.')
        return user

    def log(repository, user, action: str, details: dict[str, Any]) -> None:
        repository.try_add_log(user.username, action, json.dumps(details, ensure_ascii=False, default=str))

    def section_titles() -> dict[str, str]:
        """The sections with the titles of their modules in Interface Settings."""
        try:
            module_titles = core.app_event_module_titles()
        except Exception:  # noqa: BLE001 - the default titles stand in.
            module_titles = {}
        return {key: str(module_titles.get(feature) or SECTION_TITLES[key]) for key, feature in SECTION_FEATURES.items()}

    def scoring_environments(repository) -> list[dict[str, str]]:
        environments: dict[str, str] = {}
        try:
            for profile in repository.get_scoring_profiles()['profiles']:
                for name, scope in ((profile.get('configuration') or {}).get('scope', {}).get('environments', {}) or {}).items():
                    environments.setdefault(str(name), str((scope or {}).get('display_name') or name))
        except (ValueError, AttributeError):
            pass
        return [{'value': name, 'label': label} for name, label in environments.items()]

    @app.get('/api/reporting/complete-report/options')
    def complete_report_options(user=Depends(reporting_user)):
        repository = repository_for(user)
        tools = getattr(core, 'dashboard_reporting', None)
        dashboards = sorted(({'id': str(key), 'name': str(value.get('name') or key),
                              'nr_mode': 'SA' if str(value.get('technology') or '').casefold() == 'sa' else 'NSA'} for key, value in
                             (tools.list_dashboards(repository).items() if tools is not None else []) if isinstance(value, dict)),
                            key=lambda item: item['name'].casefold())
        return {
            'catalogue': catalogue_payload(dashboards),
            'allowed_sections': {key: core.user_has_feature(user, feature) for key, feature in SECTION_FEATURES.items()},
            'section_titles': section_titles(),
            'defaults': normalize_definition({}),
            'favourites': list_favourites(repository),
            'scoring_environments': scoring_environments(repository),
            'scorings': [{'value': key, 'label': label} for key, label in SCORINGS],
            'network_technologies': NI_TECHNOLOGIES, 'network_groupings': NI_GROUPINGS,
            'nq_granularities': NQ_GRANULARITIES,
            'area_summary_breakdowns': list(AREA_SUMMARY_BREAKDOWNS), 'area_summary_time_splits': list(AREA_SUMMARY_TIME_SPLITS),
            'can_edit': user.role in {'user-editor', 'admin', 'super-admin'},
        }

    @app.post('/api/reporting/complete-report/favourites')
    def complete_report_favourite_create(payload: FavouritePayload, user=Depends(editor_user)):
        repository = repository_for(user)
        try:
            favourite = save_favourite(repository, None, payload.name, payload.definition, user.username)
        except ValueError as exc:
            raise HTTPException(400, str(exc)) from exc
        log(repository, user, 'complete_report_favourite_saved', {'id': favourite['id'], 'name': favourite['name'], 'created': True,
                                                                 **definition_summary(favourite['definition'])})
        return {'favourite': favourite, 'favourites': list_favourites(repository)}

    @app.put('/api/reporting/complete-report/favourites/{favourite_id}')
    def complete_report_favourite_update(favourite_id: int, payload: FavouritePayload, user=Depends(editor_user)):
        repository = repository_for(user)
        try:
            favourite = save_favourite(repository, favourite_id, payload.name, payload.definition, user.username)
        except LookupError as exc:
            raise HTTPException(404, str(exc)) from exc
        except ValueError as exc:
            raise HTTPException(400, str(exc)) from exc
        log(repository, user, 'complete_report_favourite_saved', {'id': favourite['id'], 'name': favourite['name'], 'created': False,
                                                                 **definition_summary(favourite['definition'])})
        return {'favourite': favourite, 'favourites': list_favourites(repository)}

    @app.delete('/api/reporting/complete-report/favourites/{favourite_id}')
    def complete_report_favourite_delete(favourite_id: int, user=Depends(editor_user)):
        repository = repository_for(user)
        favourite = delete_favourite(repository, favourite_id)
        if favourite is None:
            raise HTTPException(404, 'The favourite Complete Report no longer exists.')
        log(repository, user, 'complete_report_favourite_deleted', {'id': favourite_id, 'name': favourite['name']})
        return {'favourites': list_favourites(repository)}

    def output_root() -> Path:
        return module_output_dir(core.settings.output_dir, COMPLETE_REPORTS_FOLDER)

    def run_job(job: dict[str, Any], repository, user, definition: dict[str, Any], titles: dict[str, str], reuse: bool = True) -> None:
        def progress(percent: int, message: str) -> None:
            with _jobs_lock:
                job.update(progress=max(job['progress'], min(99, percent)), message=message)

        try:
            with _jobs_lock:
                job.update(status='running', progress=2, message='Starting')
            result = build_report(core, repository, user, definition, job['format'], job['folder'], name=job['title'],
                                  section_titles=titles, progress=progress, cache_root=output_root() / SECTION_CACHE_FOLDER,
                                  reuse=reuse)
            stem = compose_file_stem(job['title'])
            content = result.word if job['format'] == 'word' and result.word is not None else result.powerpoint
            suffix = 'docx' if job['format'] == 'word' else 'pptx'
            path = job['folder'] / f'{stem}.{suffix}'
            path.write_bytes(content)
            cache_root = output_root() / SECTION_CACHE_FOLDER
            # A document an earlier export composed has its preview too.
            kept = cached_preview(cache_root, result.document_key, suffix) if result.document_reused else None
            if kept is not None:
                progress(96, 'Using the preview of the earlier export')
                pdf, pages = kept
            else:
                progress(96, 'Preparing the preview')
                from src.modules.pptx_to_docx import document_pdf, pdf_page_images
                pdf = document_pdf(content, suffix)
                pages = pdf_page_images(pdf, PREVIEW_DPI[suffix]) if pdf else []
                store_preview(cache_root, result.document_key, suffix, pdf, pages)
            if pdf:
                # Kept to render a page large when it is opened in the preview.
                (job['folder'] / 'preview.pdf').write_bytes(pdf)
            for index, image in enumerate(pages):
                (job['folder'] / f'preview-{index}.png').write_bytes(image)
            with _jobs_lock:
                job.update(status='ready', progress=100, message='Ready', file_name=path.name, path=str(path),
                           previews=len(pages), warnings=result.warnings, outline=result.outline, navigation=result.navigation,
                           reused=[titles.get(key, SECTION_TITLES[key]) for key in result.reused],
                           document_reused=result.document_reused,
                           finished_at=datetime.now().isoformat(timespec='seconds'))
            log(repository, user, 'complete_report_generated', {
                'job': job['id'], 'title': job['title'], 'format': job['format'], 'file_name': path.name,
                'slides': len(result.outline), 'warnings': result.warnings, 'reused_sections': result.reused})
        except Exception as exc:  # noqa: BLE001 - every failure is reported to the dialog and to App Events.
            message = str(getattr(exc, 'detail', exc)) or exc.__class__.__name__
            with _jobs_lock:
                job.update(status='failed', message=message, error=message, finished_at=datetime.now().isoformat(timespec='seconds'))
            log(repository, user, 'complete_report_failed', {'job': job['id'], 'title': job['title'], 'format': job['format'],
                                                             'error': message})

    @app.post('/api/reporting/complete-report/jobs')
    def complete_report_job_create(payload: JobPayload, user=Depends(reporting_user)):
        if payload.format not in FORMATS:
            raise HTTPException(400, 'Choose PowerPoint or Word.')
        repository = repository_for(user)
        definition = normalize_definition(payload.definition)
        sections = [section for section in enabled_sections(definition) if core.user_has_feature(user, SECTION_FEATURES[section['key']])]
        if not sections:
            raise HTTPException(400, 'Check at least one section with a sub-module to include in the Complete Report.')
        root = output_root()
        root.mkdir(parents=True, exist_ok=True)
        _forget_old_jobs(root)
        job_id = uuid.uuid4().hex
        folder = root / f"{datetime.now():%Y%m%d_%H%M%S} - {job_id[:8]}"
        folder.mkdir(parents=True, exist_ok=True)
        title = report_title(definition, payload.name.strip())
        job = {'id': job_id, 'status': 'queued', 'progress': 0, 'message': 'Queued', 'format': payload.format, 'file_name': '',
               'previews': 0, 'warnings': [], 'outline': [], 'created_at': datetime.now().isoformat(timespec='seconds'),
               'finished_at': '', 'title': title, 'error': '', 'reused': [], 'document_reused': False, 'navigation': [], 'folder': folder, 'path': '', 'username': user.username,
               'workspace_id': core.active_workspace.id}
        with _jobs_lock:
            _jobs[job_id] = job
        log(repository, user, 'complete_report_requested', {'job': job_id, 'title': title, 'format': payload.format,
                                                           'favourite': payload.name.strip(), 'refresh': payload.refresh,
                                                           **definition_summary(definition)})
        Thread(target=run_job, args=(job, repository, user, definition, section_titles(), not payload.refresh), daemon=True,
               name=f'complete-report-{job_id[:8]}').start()
        return {'job': _public(job)}

    def job_or_404(job_id: str, user) -> dict[str, Any]:
        with _jobs_lock:
            job = _jobs.get(job_id)
        if job is None or (job['username'] != user.username and user.role != 'super-admin'):
            raise HTTPException(404, 'The Complete Report is no longer available; export it again.')
        return job

    @app.get('/api/reporting/complete-report/jobs/{job_id}')
    def complete_report_job(job_id: str, user=Depends(reporting_user)):
        job = job_or_404(job_id, user)
        with _jobs_lock:
            return {'job': _public(job)}

    @app.get('/api/reporting/complete-report/jobs/{job_id}/preview/{index}')
    def complete_report_preview(job_id: str, index: int, large: bool = False, user=Depends(reporting_user)):
        """A page of the preview; ``large`` renders it at a higher resolution (once) to open it on the whole screen."""
        job = job_or_404(job_id, user)
        path = job['folder'] / f"preview-{'large-' if large else ''}{int(index)}.png"
        pdf = job['folder'] / 'preview.pdf'
        if large and not path.is_file() and pdf.is_file():
            from src.modules.pptx_to_docx import pdf_page_images
            suffix = 'docx' if job['format'] == 'word' else 'pptx'
            images = pdf_page_images(pdf.read_bytes(), LARGE_PREVIEW_DPI[suffix], [int(index)])
            if images:
                path.write_bytes(images[0])
        if large and not path.is_file():
            path = job['folder'] / f'preview-{int(index)}.png'
        if not path.is_file():
            raise HTTPException(404, 'This page has no preview.')
        return Response(path.read_bytes(), media_type='image/png', headers={'Cache-Control': 'private, max-age=3600'})

    @app.get('/api/reporting/complete-report/jobs/{job_id}/download')
    def complete_report_download(job_id: str, user=Depends(reporting_user)):
        job = job_or_404(job_id, user)
        if job['status'] != 'ready' or not job['path'] or not Path(job['path']).is_file():
            raise HTTPException(409, 'The Complete Report is not ready.')
        repository = repository_for(user)
        log(repository, user, 'complete_report_downloaded', {'job': job_id, 'title': job['title'], 'file_name': job['file_name']})
        media = ('application/vnd.openxmlformats-officedocument.wordprocessingml.document' if job['format'] == 'word'
                 else 'application/vnd.openxmlformats-officedocument.presentationml.presentation')
        return FileResponse(job['path'], media_type=media, filename=job['file_name'])

